// Function to parse raw map data
const parseMapData = (rawMap) => {
  const map = Array(20).fill().map(() => Array(30).fill(0));
  const overlayLayer = Array(20).fill().map(() => Array(30).fill(null));
  const secondOverlayLayer = Array(20).fill().map(() => Array(30).fill(null));
  const chests = []; // Store chest positions

  for (let row = 0; row < 20; row++) {
    for (let col = 0; col < 30; col++) {
      let tile = rawMap[row][col];
      let isChest = false;

      // Check if the tile is a string (e.g., '12/*itemID41*/'/*C*/)
      if (typeof tile === 'string') {
        // Check for chest comment
        if (tile.includes('/* CHEST */') || tile.includes('/*CHEST*/')) {
          isChest = true;
          chests.push({ row, col });
        }

        // Extract the base tile value (before any comments)
        const tileValueMatch = tile.match(/^\d+/);
        tile = tileValueMatch ? parseInt(tileValueMatch[0]) : 0;

        // Extract item ID if present (e.g., 'itemID41')
        const itemMatch = tile.match(/itemID(\d+)/);
        if (itemMatch) {
          const itemId = parseInt(itemMatch[1]);
          overlayLayer[row][col] = itemId; // Place item in overlay layer
        }
      }

      map[row][col] = tile;

      // If it's a chest, place a chest tile in the overlay layer
      if (isChest) {
        overlayLayer[row][col] = 36; // Use tile ID 36 for chests (can adjust based on your sprite sheet)
      }
    }
  }

  return { map, overlayLayer, secondOverlayLayer, chests };
};

